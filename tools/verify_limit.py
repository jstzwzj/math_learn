#!/usr/bin/env python3
"""用数值计算验证第 01 讲的三个结论：
1. 数列 n/(n+1) 收敛到 1
2. lim_{x->0} sin(x)/x = 1（第一个重要极限）
3. 导数是"差商的极限"（提前预告第 05 讲）

运行: python3 tools/verify_limit.py
依赖: 仅标准库 math，无需安装任何东西
"""

import math

def section(title: str) -> None:
    print(f"\n{'=' * 50}\n{title}\n{'=' * 50}")

# ---------------------------------------------------------------
section("1. 数列 n/(n+1) -> 1：看趋势如何逼近")

for n in [1, 10, 100, 10_000, 1_000_000]:
    print(f"n = {n:>9,}    n/(n+1) = {n / (n + 1):.9f}")

print("\n观察：每项都小于 1，但与 1 的差距 ~ 1/n，随 n 增大消失。")

# ---------------------------------------------------------------
section("2. lim_{x->0} sin(x)/x = 1：从两边逼近")

for x in [0.5, 0.1, 0.01, 0.001, -0.001, -0.01, -0.1]:
    print(f"x = {x:>7}    sin(x)/x = {math.sin(x) / x:.9f}")

print("\n观察：从正负两侧逼近 0，比值都逼近 1（注意 x 必须用弧度）。")

# ---------------------------------------------------------------
section("3. 导数 = 差商的极限：以 f(x) = x^2 在 x=3 处为例")
print("导数的定义: f'(a) = lim_{h->0} (f(a+h) - f(a)) / h")
print("f(x) = x^2 时，f'(3) 理论值 = 2*3 = 6\n")

for h in [0.1, 0.01, 0.001, 0.0001]:
    quotient = ((3 + h) ** 2 - 3**2) / h
    print(f"h = {h:>7}    (f(3+h)-f(3))/h = {quotient:.6f}")

print("\n观察：h 越小，差商越接近 6。'瞬时变化率'就是这样定义出来的。")

# ---------------------------------------------------------------
section("4. 反例：不是所有极限都存在—— sin(1/x) 在 x->0 时震荡")

for x in [0.1, 0.01, 0.001, 0.0001]:
    print(f"x = {x:>7}    sin(1/x) = {math.sin(1 / x):+.6f}")

print("\n观察：x 变小，值在 -1 到 1 之间乱跳，不趋于任何数。")
print("所以'极限存在'是需要证明的事，不是当然的。")
