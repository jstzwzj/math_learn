#!/usr/bin/env python3
"""用数值计算验证第 03 讲的结论：第二个重要极限与自然常数 e。

运行（macOS/Linux）: python3 tools/verify_e_limit.py
运行（Windows）:     python tools\verify_e_limit.py
依赖: 仅标准库 math，无需安装任何东西

四个验证（外加一个浮点彩蛋）:
  1. 连续复利：付息次数 n 越大，(1+1/n)^n 越逼近 e（但涨得越来越慢）
  2. 两侧逼近：x -> +∞ 与 x -> -∞，(1+1/x)^x 都逼近 e
  3. 等价形式：x -> 0 时 (1+x)^(1/x) -> e（正负两侧）
  4. 1^∞ 型实战：(1+2/x)^x -> e^2、(1-1/x)^x -> 1/e
  5. 彩蛋：n = 10^15 时直接算 (1+1/n)**n 的浮点翻车现场，及 log1p 稳定写法
"""

import math
import sys

# Windows 老控制台兜底：打不出的字符用 "?" 代替而不是崩溃（PS7 / macOS / Linux 无影响）
sys.stdout.reconfigure(errors="replace")


def section(title: str) -> None:
    print(f"\n{'=' * 50}\n{title}\n{'=' * 50}")


# ---------------------------------------------------------------
section("1. 连续复利：(1+1/n)^n 随付息次数 n 逼近 e")

print("本金 1 元、年利率 100%，一年分 n 期利滚利：\n")
print(f"{'n（期数）':>14}  {'(1+1/n)^n':>18}  {'与 e 的差距':>12}")
labels = {
    1: "一年一次", 2: "半年一次", 4: "每季度", 12: "每月",
    365: "每天", 8760: "每小时", 525_600: "每分钟", 31_536_000: "每秒",
}
for n, label in labels.items():
    value = (1 + 1 / n) ** n
    print(f"{label:>6} n={n:>10}  {value:>18.12f}  {math.e - value:>12.6e}")

print(f"\n对照：math.e = {math.e:.12f}")
print("观察：n 越大越贴近 e，但差距缩小得越来越慢——这就是'逼近'而不是'到达'。")
print("e 和 π 一样，是被逼近过程'逼'出来的数，不是被定义出来的。")

# ---------------------------------------------------------------
section("2. 两侧逼近：x -> +∞ 和 x -> -∞ 都是 e")

for x in [10**3, 10**4, 10**5, 10**6]:
    plus = (1 + 1 / x) ** x
    minus = (1 - 1 / x) ** (-x)
    print(f"|x| = {x:<8}  x=+|x|: {plus:.12f}    x=-|x|: {minus:.12f}")

print("\n观察：两个方向都收敛到同一个数。第二重要极限对 x -> ±∞ 都成立。")

# ---------------------------------------------------------------
section("3. 等价形式：x -> 0 时 (1+x)^(1/x) -> e")

for x in [0.1, 0.01, 0.001, 0.0001]:
    pos = (1 + x) ** (1 / x)
    neg = (1 - x) ** (-1 / x)
    print(f"x = {x:<8}  从正侧: {pos:.12f}    从负侧: {neg:.12f}")

print(f"\n对照：math.e = {math.e:.12f}")
print("观察：这是做题时最常用的形态——底数 -> 1，指数 -> ∞，且两者互为倒数。")

# ---------------------------------------------------------------
section("4. 1^∞ 型实战：(1+2/x)^x -> e^2，(1-1/x)^x -> 1/e")

print("套路：答案 = e^(lim (底数-1)×指数)。前者乘积 -> 2，后者 -> -1。\n")
for x in [10, 100, 1000, 10000]:
    a = (1 + 2 / x) ** x
    b = (1 - 1 / x) ** x
    print(f"x = {x:<7}  (1+2/x)^x = {a:.9f}  (目标 e^2 = {math.e**2:.9f})"
          f"    (1-1/x)^x = {b:.9f}  (目标 1/e = {1/math.e:.9f})")

print("\n观察：'1 的无穷次方'不是 1——它是底数与指数拔河出来的 e^A。")

# ---------------------------------------------------------------
section("5. 彩蛋：n 大到 10^15，直接算 (1+1/n)**n 会翻车")

n = 10**15
direct = (1 + 1 / n) ** n
stable = math.exp(n * math.log1p(1 / n))
print(f"直接算 (1+1/n)**n          = {direct:.12f}")
print(f"稳定写法 exp(n*log1p(1/n)) = {stable:.12f}")
print(f"math.e                     = {math.e:.12f}")

print("\n原因：1 + 1/n 与 1 的差已逼近双精度极限，直接相加损失大量有效位；")
print("math.log1p 专门为 log(1+小数) 设计，绕开了这次'灾难性抵消'（第 02 讲的老朋友）。")
